/**
 * 根据错误码获取中文提示，优先使用后端返回的 message（可能含动态参数）
 */
export function getErrorMessage(code: number | undefined | null, backendMessage?: string): string {
  if (backendMessage) return backendMessage
  if (code != null && ERROR_CODE_MAP[code]) return ERROR_CODE_MAP[code]
  return '网络请求失败，请稍后重试'
}

